export function normalizeText(text = '') {
  return String(text)
    .normalize('NFC')
    .trim()
    .replace(/\s+/g, ' ')
    .toLocaleLowerCase('ar');
}

export function findAutoReply(text = '') {
  const normalized = normalizeText(text);
  const groups = [...AUTO_REPLIES].sort((a, b) => {
    const aLen = Math.max(...a.triggers.map(t => normalizeText(t).length));
    const bLen = Math.max(...b.triggers.map(t => normalizeText(t).length));
    return bLen - aLen;
  });

  for (const group of groups) {
    if (group.triggers.some(trigger => normalizeText(trigger) === normalized)) {
      const choices = group.replies;
      return choices[Math.floor(Math.random() * choices.length)];
    }
  }
  return null;
}
