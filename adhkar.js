export function randomDhikr(type, previous = '') {
  const list = ADHKAR[type] || ADHKAR.quran;
  const choices = list.filter(item => item !== previous);
  return (choices.length ? choices : list)[Math.floor(Math.random() * (choices.length ? choices.length : list.length))];
}
