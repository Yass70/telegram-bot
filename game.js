export function normalizeGameAnswer(value) {
  return String(value ?? '')
    .trim()
    .toLocaleLowerCase('ar')
    .replace(/[ًٌٍَُِّْـ]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ');
}

function nextQuestion(game) {
  if (game.usedQuestions.length >= gameQuestions.length) {
    return null;
  }

  let index;
  do {
    index = Math.floor(Math.random() * gameQuestions.length);
  } while (game.usedQuestions.includes(index));

  return index;
}

function showNextQuestion(game, index) {
  game.usedQuestions.push(index);
  game.round++;
  game.questionIndex = index;
  game.answer = gameQuestions[index].a;

  return `❓ السؤال ${game.round}/${game.totalRounds}:\n${gameQuestions[index].q}`;
}

export async function handleGroupGame(ctx, g, db, save, userKey) {
  const text = ctx.message.text.trim();
  const normalized = normalizeGameAnswer(text);
  const isStart = ['العاب', 'لعبه'].includes(normalized);

  if (isStart) {
    if (g.game?.active) {
      await ctx.reply('🎮 اللعبة شغّالة بالفعل! جاوبوا على السؤال الحالي 🐈‍⬛');
      return true;
    }

    const firstIndex = Math.floor(Math.random() * gameQuestions.length);

    g.game = {
      active: true,
      round: 1,
      totalRounds: 10,
      usedQuestions: [firstIndex],
      questionIndex: firstIndex,
      answer: gameQuestions[firstIndex].a,
      scores: {},
      names: {}
    };

    save();

    await ctx.reply(
      `🐈‍⬛🔥 تحدّي نغنوغ بدأ!\n\n` +
      `📋 10 أسئلة، وأول واحد يجاوب صح ياخذ نقطة!\n` +
      `🏆 النقاط تنحفظ بحسابه.\n\n` +
      `❓ السؤال 1/10:\n${gameQuestions[firstIndex].q}`
    );

    return true;
  }

  if (!g.game?.active) return false;

  if (['التالي', 'تالي'].includes(normalized)) {
    const skippedAnswer = g.game.answer;

    if (g.game.round >= g.game.totalRounds) {
      g.game = null;
      save();

      await ctx.reply(
        `🏁 انتهى تحدّي نغنوغ!\n` +
        `💡 جواب السؤال الأخير كان: ${skippedAnswer}\n` +
        `🎮 انتهت الأسئلة العشرة!`
      );

      return true;
    }

    const index = nextQuestion(g.game);

    if (index === null) {
      g.game = null;
      save();
      await ctx.reply('🏁 انتهت الأسئلة المتاحة باللعبة!');
      return true;
    }

    const question = showNextQuestion(g.game, index);
    save();

    await ctx.reply(
      `⏭️ تم تخطي السؤال!\n` +
      `💡 الإجابة الصحيحة: ${skippedAnswer}\n\n` +
      question
    );

    return true;
  }

  const answerVal = normalizeGameAnswer(text);
  const correctAnswer = normalizeGameAnswer(g.game.answer);

  if (answerVal !== correctAnswer) return true;

  const uid = userKey(ctx);
  const name = ctx.from.first_name || 'عضو';

  g.game.scores[uid] = Number(g.game.scores[uid] || 0) + 1;
  g.game.names[uid] = name;
  db.points[uid] = Number(db.points[uid] || 0) + 1;

  const winnerMessage =
    `✅ إجابة صحيحة!\n` +
    `🏅 الفائز بالسؤال: ${name}\n` +
    `⭐ نقاطه بهالجولة: ${g.game.scores[uid]}\n` +
    `💎 نقاطه الدائمة: ${db.points[uid]}`;

  if (g.game.round >= g.game.totalRounds) {
    const scores = Object.entries(g.game.scores);
    const maxScore = Math.max(...scores.map(([, score]) => score));
    const winners = scores.filter(([, score]) => score === maxScore);

    let finalMessage = '\n\n🏁 انتهى تحدّي نغنوغ!\n\n';

    if (winners.length === 1) {
      finalMessage += `👑 بطل التحدّي: ${g.game.names[winners[0][0]]}\n`;
    } else {
      finalMessage += '🤝 تعادل بين:\n';
      finalMessage += winners.map(([id]) => `• ${g.game.names[id]}`).join('\n') + '\n';
    }

    finalMessage += '🏆 النتيجة النهائية:\n';
    finalMessage += scores
      .sort((a, b) => b[1] - a[1])
      .map(([id, score]) => `• ${g.game.names[id]}: ${score} نقطة`)
      .join('\n');

    g.game = null;
    save();
    await ctx.reply(winnerMessage + finalMessage);
    return true;
  }

  const index = nextQuestion(g.game);

  if (index === null) {
    g.game = null;
    save();
    await ctx.reply(winnerMessage + '\n\n🏁 انتهت الأسئلة المتاحة باللعبة!');
    return true;
  }

  const question = showNextQuestion(g.game, index);
  save();

  await ctx.reply(`${winnerMessage}\n\n${question}`);
  return true;
}
